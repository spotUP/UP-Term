#!/usr/bin/env python3
"""Regenerate engine/rip_fontdata.inc from the Hershey .jhf files (RIP-3b).

usage: python3 -I tools/gen_rip_font.py <dir with rowmant.jhf rowmans.jhf futural.jhf gothiceng.jhf> > engine/rip_fontdata.inc

Source: https://github.com/kamalmostafa/hershey-fonts (hershey-fonts/*.jhf, James Hurt's
conversion of A. V. Hershey's 1967 NBS data). Only ASCII 32..126 (lines 1..95) are kept.
Each glyph becomes one C string: left, right, then the vertex pairs (a space pair "  R" pen
up marker is kept as " R"), coordinates as in the .jhf file (letter - 'R').
"""
import sys, os

FONTS = [("triplex", "rowmant"), ("small", "rowmans"), ("sans", "futural"), ("gothic", "gothiceng")]


def esc(s):
    out = []
    for ch in s:
        if ch in '\\"?':
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def main():
    d = sys.argv[1]
    print("/* generated by tools/gen_rip_font.py -- do not edit; Hershey data, notice in rip_font.c */")
    for name, f in FONTS:
        lines = [l.rstrip("\r\n") for l in open(os.path.join(d, f + ".jhf")) if l.strip()]
        assert len(lines) >= 95, f
        print("static const char *const hf_%s[95] = {" % name)
        for i in range(95):
            l = lines[i]
            n = int(l[5:8])
            body = l[8:]
            assert len(body) == 2 * n, (f, i, n, len(body))
            print('    "%s",' % esc(body))
        print("};")


main()
