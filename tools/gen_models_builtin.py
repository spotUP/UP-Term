#!/usr/bin/env python3
"""The built-in model catalog.

  llm/models_builtin.json  <- tools/pi_models_dump.json   (--from-pi; the dump is pi-ai's own data, made by
                                                           `node tools/dump_pi_models.mjs`, never typed by hand)
  llm/models_builtin.h     <- llm/models_builtin.json     (default; the catalog as a C string, the Amiga has no file)
  --check                  both are up to date (make test runs it)

llm/models_builtin.json holds pi's fields for each model, verbatim: id, name, api, baseUrl, reasoning, input, cost
(with tiers), contextWindow, maxTokens, thinkingLevelMap, compat. The one entry pi does not have is
ollama/qwen2.5-coder:7b (the spec's example), marked "source": "not in pi".
"""
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "llm")
dump = os.path.join(here, "pi_models_dump.json")
jsn = os.path.join(root, "models_builtin.json")
hdr = os.path.join(root, "models_builtin.h")
KEYS = ["id", "name", "api", "baseUrl", "reasoning", "input", "cost", "contextWindow", "maxTokens",
        "thinkingLevelMap", "compat", "headers"]


def from_pi():
    d = json.load(open(dump))
    providers = {}
    for p, models in d["providers"].items():
        providers[p] = {"models": [{k: m[k] for k in KEYS if k in m} for m in models]}
    providers["ollama"] = {
        "baseUrl": "http://localhost:11434/v1", "api": "openai-completions",
        "models": [{"id": "qwen2.5-coder:7b", "name": "Qwen2.5 Coder 7B", "contextWindow": 32768,
                    "maxTokens": 8192, "source": "not in pi"}]}
    return {"source": d["pi"], "providers": providers}


def json_text(obj):
    return json.dumps(obj, indent=1) + "\n"


def header_text():
    body = json.dumps(json.load(open(jsn)), separators=(",", ":"))
    data = body.encode() + b"\0"
    rows = [", ".join("%d" % c for c in data[i:i + 24]) for i in range(0, len(data), 24)]
    out = "/* generated by tools/gen_models_builtin.py from llm/models_builtin.json: do not edit */\n"
    return out + "static const char llm_models_builtin[] = {\n    " + ",\n    ".join(rows) + "\n};\n"


if "--from-pi" in sys.argv:
    open(jsn, "w").write(json_text(from_pi()))
if "--check" in sys.argv:
    ok = open(jsn).read() == json_text(from_pi())
    if not ok:
        sys.stderr.write("llm/models_builtin.json differs from tools/pi_models_dump.json: gen_models_builtin.py --from-pi\n")
    ok = ok and open(hdr).read() == header_text()
    sys.exit(0 if ok else 1)
open(hdr, "w").write(header_text())
