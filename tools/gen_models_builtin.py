#!/usr/bin/env python3
"""llm/models_builtin.json -> llm/models_builtin.h (the catalog as a C string; the Amiga has no file for it)."""
import json, os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "llm")
src = open(os.path.join(root, "models_builtin.json")).read()
json.loads(src)
body = json.dumps(json.loads(src), separators=(",", ":"))
data = body.encode() + b"\0"
rows = [", ".join("%d" % c for c in data[i:i + 24]) for i in range(0, len(data), 24)]
out = "/* generated by tools/gen_models_builtin.py from llm/models_builtin.json: do not edit */\n"
out += "static const char llm_models_builtin[] = {\n    " + ",\n    ".join(rows) + "\n};\n"
dst = os.path.join(root, "models_builtin.h")
if "--check" in sys.argv:
    sys.exit(0 if open(dst).read() == out else 1)
open(dst, "w").write(out)
