#!/usr/bin/env python3
"""Generate the TrueType rasterizer test data (plan R0.2, R0.3).

Subsets Symbols Nerd Font Mono 3.5.1 to a few code points, writes
tests/data/symnerd_subset.h, builds tools/fonts/ft_oracle.c against FreeType
and writes tests/data/ttf_golden.h from its output.  Run: make ttf-testdata
"""
import os, subprocess, sys, tempfile
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.environ.get('SYMNERD_TTF', os.path.join(ROOT, 'build/third_party/f1/SymNerdMono.ttf'))
DATA = os.path.join(ROOT, 'tests/data')
CPS = [0xE0A0, 0xE615, 0xEA74, 0xEBCF, 0xF011, 0xF021, 0xF003B, 0xF09D1, 0xF0249, 0xF14DE, 0xF0B4C]
# U+2588 was requested but SymNerdMono.ttf 3.5.1 has no glyph for it (verified in its cmap), so it is not part of the data.
SIZES = [(8, 16, 12), (16, 32, 25)]
BLANK_OK = set()


def build_subset(tmp):
    opt = subset.Options()
    opt.layout_features = []
    opt.hinting = True
    opt.notdef_outline = True
    opt.notdef_glyph = True
    opt.glyph_names = False
    opt.name_IDs = []
    opt.drop_tables += ['GSUB', 'GPOS', 'GDEF', 'DSIG', 'name', 'post', 'OS/2', 'kern']
    font = subset.load_font(SRC, opt)
    s = subset.Subsetter(opt)
    s.populate(unicodes=CPS)
    s.subset(font)
    # the subsetter may drop format 12 when every code point is in the BMP
    cm = font['cmap']
    have = {(t.format, t.platformID, t.platEncID) for t in cm.tables}
    if (12, 3, 10) not in have:
        from fontTools.ttLib.tables._c_m_a_p import CmapSubtable
        t4 = [t for t in cm.tables if t.format == 4][0]
        full = {}
        for cp in CPS:
            full[cp] = font.getBestCmap()[cp]
        t12 = CmapSubtable.newSubtable(12)
        t12.platformID, t12.platEncID, t12.language, t12.cmap = 3, 10, 0, full
        cm.tables.append(t12)
        print('format 12 forced')
    for t in cm.tables:
        t.cmap = {k: v for k, v in t.cmap.items() if k in CPS}
    path = os.path.join(tmp, 'subset.ttf')
    font.save(path)
    chk = TTFont(path)
    fm = {(t.format, t.platformID, t.platEncID) for t in chk['cmap'].tables}
    assert any(f == 4 for f, _, _ in fm) and (12, 3, 10) in fm, fm
    bc = chk.getBestCmap()
    assert all(cp in bc for cp in CPS), 'missing code points'
    return path


def write_subset_h(path):
    b = open(path, 'rb').read()
    out = ['/* generated by tools/fonts/make_ttf_testdata.py from Symbols Nerd Font Mono 3.5.1',
           '   (SIL OFL 1.1, see tests/data/OFL-SymbolsNerdFont.txt); do not edit */',
           'static const unsigned char symnerd_subset[] = {']
    for i in range(0, len(b), 16):
        out.append('  ' + ','.join('0x%02x' % x for x in b[i:i + 16]) + (',' if i + 16 < len(b) else ''))
    out.append('};')
    out.append('#define SYMNERD_SUBSET_LEN %d' % len(b))
    open(os.path.join(DATA, 'symnerd_subset.h'), 'w').write('\n'.join(out) + '\n')
    return len(b)


def main():
    os.makedirs(DATA, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        ttf = build_subset(tmp)
        n = write_subset_h(ttf)
        print('subset bytes', n)
        exe = os.path.join(tmp, 'ft_oracle')
        flags = subprocess.check_output(['pkg-config', '--cflags', '--libs', 'freetype2'], text=True).split()
        ver = subprocess.check_output(['pkg-config', '--modversion', 'freetype2'], text=True).strip()
        try:
            bv = subprocess.check_output(['brew', 'list', '--versions', 'freetype'], text=True).split()[-1]
            ver = '%s, libtool %s' % (bv, ver)
        except Exception:
            pass
        subprocess.check_call(['cc', '-O1', '-o', exe, os.path.join(ROOT, 'tools/fonts/ft_oracle.c')] + flags)
        hexcps = ['%X' % c for c in CPS]
        ents, decls = [], []
        for (w, h, bl) in SIZES:
            outp = subprocess.check_output([exe, ttf, str(w), str(h), str(bl)] + hexcps, text=True)
            for line in outp.splitlines():
                cps, hx = line.split()
                cov = bytes.fromhex(hx)
                assert len(cov) == w * h
                cp = int(cps, 16)
                if not any(cov):
                    print('BLANK golden: U+%04X %dx%d' % (cp, w, h))
                name = 'golden_%04x_%dx%d' % (cp, w, h)
                body = []
                for i in range(0, len(cov), 16):
                    body.append('  ' + ','.join('0x%02x' % x for x in cov[i:i + 16]))
                decls.append('static const unsigned char %s[%d] = {\n%s\n};' % (name, len(cov), ',\n'.join(body)))
                ents.append('  { 0x%XUL, %d, %d, %d, %s }' % (cp, w, h, bl, name))
        assert len(ents) == 2 * len(CPS)
        txt = ['/* generated by tools/fonts/make_ttf_testdata.py with tools/fonts/ft_oracle.c (FreeType %s, no hinting); do not edit */' % ver,
               'typedef struct ttf_golden { unsigned long cp; int w, h, baseline; const unsigned char *cov; } ttf_golden;']
        txt += decls
        txt.append('static const ttf_golden ttf_goldens[] = {\n' + ',\n'.join(ents) + '\n};')
        txt.append('#define TTF_GOLDENS %d' % len(ents))
        open(os.path.join(DATA, 'ttf_golden.h'), 'w').write('\n'.join(txt) + '\n')
        print('golden written, FreeType', ver)


main()
