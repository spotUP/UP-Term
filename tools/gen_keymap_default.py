#!/usr/bin/env python3
"""dist/keymap -> a C string constant (build/amiga/keymap_default.inc).

The handler keeps the shipped keymap compiled in: the table it uses when
ENV:up-term/keymap and ENVARC:up-term/keymap are both missing or newer than
this build understands. One source: the file in dist/, never a second copy.
Usage: gen_keymap_default.py <dist/keymap> <out.inc>"""
import sys

src, out = sys.argv[1], sys.argv[2]
data = open(src, "rb").read()
lines = data.split(b"\n")
if lines and lines[-1] == b"":
    lines.pop()
with open(out, "w") as f:
    f.write("/* generated by tools/gen_keymap_default.py from dist/keymap: do not edit */\n")
    f.write("static const char km_default_text[] =\n")
    for ln in lines:
        s = ""
        for b in ln + b"\n":
            if b == 0x22:
                s += '\\"'
            elif b == 0x5C:
                s += "\\\\"
            elif b == 0x0A:
                s += "\\n"
            elif b == 0x0D:
                s += "\\r"
            elif 0x20 <= b < 0x7F:
                s += chr(b)
            else:
                s += "\\%03o" % b
        f.write('    "%s"\n' % s)
    f.write("    ;\n")
