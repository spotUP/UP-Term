#!/usr/bin/env python3
"""Generate claude/unorm_tab.h: the Unicode data of NFKC (claude/unorm.c).

amiga-pi's edit matches as pi does, and pi normalises with JavaScript's
String.prototype.normalize("NFKC") (pi f10993bc tools/edit-diff.ts
normalizeForFuzzyMatch). The tables come from Python's unicodedata, which
must be Unicode 16.0.0 (node 24's ICU, what pi runs on, is 16.0 too):

  un_d*     every code point whose full compatibility decomposition (NFKD)
            differs from itself, Hangul syllables excepted (algorithmic),
            sorted, with that decomposition as UTF-8
  un_ccc*   the canonical combining classes that are not 0, as runs
  un_c*     the primary composites: a + b -> c where c's canonical
            decomposition is a b and NFC(a b) is c (the composition
            exclusions and singletons are left out by that test)
BMP and astral entries apart, so most keys are 16 bits.

    python3 -I tools/gen_unorm.py            (writes claude/unorm_tab.h)
"""
import os
import sys
import unicodedata as u

VERSION = "16.0.0"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "claude", "unorm_tab.h")


def cps():
    for c in range(0x110000):
        if 0xD800 <= c < 0xE000:
            continue
        yield c


def main():
    if u.unidata_version != VERSION:
        sys.exit("[ERROR] Python's unicodedata is %s, the table needs %s" % (u.unidata_version, VERSION))
    dec = []
    for c in cps():
        if 0xAC00 <= c <= 0xD7A3:
            continue
        ch = chr(c)
        d = u.normalize("NFKD", ch)
        if d != ch:
            dec.append((c, d.encode("utf-8")))
    runs = []
    for c in cps():
        k = u.combining(chr(c))
        if not k:
            continue
        if runs and runs[-1][0] + runs[-1][1] == c and runs[-1][2] == k:
            runs[-1][1] += 1
        else:
            runs.append([c, 1, k])
    pairs = []
    for c in cps():
        d = u.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        p = [int(x, 16) for x in d.split()]
        if len(p) == 2 and u.normalize("NFC", chr(p[0]) + chr(p[1])) == chr(c):
            pairs.append((p[0], p[1], c))
    pairs.sort()

    data = bytearray()
    bmp, ast = [], []
    for c, d in dec:
        (bmp if c < 0x10000 else ast).append((c, len(data)))
        data += d
    assert len(data) < 65536
    pb = [p for p in pairs if max(p) < 0x10000]
    pa = [p for p in pairs if max(p) >= 0x10000]

    def arr(ctype, name, vals, per=12, fmt="0x%X"):
        lines = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
        for i in range(0, len(vals), per):
            lines.append("    " + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
        lines.append("};")
        return "\n".join(lines)

    out = ["/* Generated by tools/gen_unorm.py from Unicode %s (Python's unicodedata). Do not edit. */" % VERSION,
           "#define UN_DBMP %d" % len(bmp), "#define UN_DAST %d" % len(ast), "#define UN_CCC %d" % len(runs),
           "#define UN_CBMP %d" % len(pb), "#define UN_CAST %d" % len(pa), "#define UN_DATA %d" % len(data)]
    out.append(arr("unsigned short", "un_dbmp", [c for c, _ in bmp]))
    out.append(arr("unsigned short", "un_dbmp_at", [o for _, o in bmp] + [len(data) if not ast else ast[0][1]]))
    out.append(arr("unsigned long", "un_dast", [c for c, _ in ast] or [0]))
    out.append(arr("unsigned short", "un_dast_at", [o for _, o in ast] + [len(data)]))
    out.append(arr("unsigned char", "un_data", list(data), 16))
    out.append(arr("unsigned long", "un_ccc_cp", [r[0] for r in runs]))
    out.append(arr("unsigned char", "un_ccc_n", [r[1] for r in runs], 16, "%d"))
    out.append(arr("unsigned char", "un_ccc_v", [r[2] for r in runs], 16, "%d"))
    out.append(arr("unsigned short", "un_cbmp", [x for p in pb for x in p], 12))
    out.append(arr("unsigned long", "un_cast", [x for p in pa for x in p] or [0], 12))
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("unorm_tab.h: %d decompositions (%d BMP), %d bytes of them, %d ccc runs, %d compositions" % (
        len(dec), len(bmp), len(data), len(runs), len(pairs)))


if __name__ == "__main__":
    main()
