#!/usr/bin/env python3
"""dist/amarchy.help -> build/amiga/amhelp.inc (C strings for amarchy-gui) and the GETTING STARTED section of
man/amarchy.1 (between the marker comments).

One source: the sections [welcome] and [help] of dist/amarchy.help. The C text keeps its {key:...} / {menu:...}
placeholders (the program fills them from the live keymap, amarchy/help_core.c). The man page cannot know the
user's keymap, so it shows the keys of the shipped dist/keymap, spelled as the program spells them.
Usage: gen_amarchy_help.py <dist/amarchy.help> <dist/keymap> <out.inc>
       gen_amarchy_help.py --man <dist/amarchy.help> <dist/keymap> <man/amarchy.1>   (splice, rewrite the file)
       gen_amarchy_help.py --check <dist/amarchy.help> <dist/keymap> <man/amarchy.1> (exit 1 when the man page drifts)"""
import re
import sys

BEGIN = ".\\\" BEGIN GENERATED amarchy.help: do not edit, run tools/gen_amarchy_help.py --man\n"
END = ".\\\" END GENERATED amarchy.help\n"
PH = re.compile(r"\{(key|menu):([^}]*)\}")


def sections(text):
    out, cur = {}, None
    for ln in text.split("\n"):
        if ln.startswith("["):
            cur = ln[1:ln.index("]")]
            out[cur] = []
        elif cur is not None:
            out[cur].append(ln)
    for k in out:
        while out[k] and out[k][-1] == "":
            out[k].pop()
    return out


def parse_keymap(text):
    binds, menu, sec = {}, {}, None
    for ln in text.split("\n"):
        s = ln.split(";", 1)[0].strip() if not ln.startswith("[") else ln.strip()
        if not s:
            continue
        if s.startswith("["):
            sec = s
            continue
        if "=" not in s:
            continue
        lhs, rhs = [x.strip() for x in s.split("=", 1)]
        if sec == "[bind]":
            act = rhs.split("|")[0].strip()
            binds.setdefault(act, lhs)
        elif sec == "[menu]":
            menu[lhs] = rhs.split("|")[0].strip()
    return binds, menu


def spec(lhs):
    return "+".join(p.capitalize() for p in lhs.split("+"))


def menu_path(menu, mid):
    parts = mid.split(".")
    out = []
    for i in range(len(parts)):
        pid = ".".join(parts[: i + 1])
        out.append(menu.get(pid) or parts[i][:1].upper() + parts[i][1:])
    return " > ".join(out)


def render(lines, binds, menu):
    def sub(m):
        if m.group(1) == "key":
            return spec(binds[m.group(2)]) if m.group(2) in binds else "(unbound)"
        return menu_path(menu, m.group(2)) if m.group(2) else "(unbound)"
    return [PH.sub(sub, ln) for ln in lines]


def cstr(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def man_section(sec, binds, menu):
    """Welcome text as a literal block per paragraph, then each help topic: a .Ss heading and a body."""
    out = [".Sh GETTING STARTED"]
    wl = render(sec["welcome"], binds, menu)
    paras, cur = [], []
    for ln in wl + [""]:
        if ln == "":
            if cur:
                paras.append(cur)
            cur = []
        else:
            cur.append(ln)
    for p in paras[1:]:  # the first paragraph is the window title
        if p[0].startswith(("Open the menu", "Snap a window")) or ":" in p[0][:24]:
            out.append(".Bd -literal -offset indent")
            out += [esc(x) for x in p]
            out.append(".Ed")
        else:
            out += [esc(x) for x in p]
        out.append(".Pp")
    hl = render(sec["help"], binds, menu)[1:]
    first = True
    for ln in hl:
        if ln.isupper() and ln.strip():
            out.append(".Ss " + ln.capitalize().replace("Arexx", "ARexx"))
            first = True
        elif ln == "":
            if out[-1] != ".Pp":
                out.append(".Pp")
        else:
            out.append(esc(ln))
    while out[-1] == ".Pp":
        out.pop()
    return "\n".join(out) + "\n"


def esc(ln):
    if ln.startswith((".", "'")):
        ln = "\\&" + ln
    return ln.replace("\\", "\\\\") if "\\&" not in ln else ln


def splice(man, block):
    a, b = man.find(BEGIN), man.find(END)
    if a < 0 or b < 0:
        sys.exit("[ERROR] marker comments missing in the man page")
    return man[:a + len(BEGIN)] + block + man[b:]


def main():
    args = sys.argv[1:]
    mode = "inc"
    if args and args[0] in ("--man", "--check"):
        mode, args = args[0], args[1:]
    src, kmap, out = args
    sec = sections(open(src, encoding="ascii").read())
    binds, menu = parse_keymap(open(kmap, encoding="ascii").read())
    if mode == "inc":
        with open(out, "w") as f:
            f.write("/* generated by tools/gen_amarchy_help.py from dist/amarchy.help: do not edit */\n")
            for name in ("welcome", "help"):
                f.write("static const char amhelp_%s[] =\n" % name)
                for ln in sec[name]:
                    f.write('    "%s\\n"\n' % cstr(ln))
                f.write("    ;\n")
        return
    man = open(out, encoding="ascii").read()
    new = splice(man, man_section(sec, binds, menu))
    if mode == "--check":
        if new != man:
            print("[FAIL] man/amarchy.1 GETTING STARTED differs from dist/amarchy.help: run tools/gen_amarchy_help.py --man")
            sys.exit(1)
        print("[OK] man/amarchy.1 matches dist/amarchy.help")
    else:
        open(out, "w", encoding="ascii").write(new)


main()
