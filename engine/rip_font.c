/* RIP-3b: Hershey stroke fonts for the BGI font styles 1..4 (the host option "stroke", rip.h).
 * Included into vtengine.c before rip_draw.c; the segments go through the caller's line
 * primitive (rip_draw.c), this file only turns a glyph into segments.
 *
 * Style mapping (BGI Y font number -> Hershey face):
 *   1 triplex      -> Roman Triplex          (rowmant.jhf)
 *   2 small        -> Roman Simplex          (rowmans.jhf; the light single-stroke face)
 *   3 sans-serif   -> Sans-serif Simplex     (futural.jhf, "Futura L")
 *   4 gothic       -> Gothic English Triplex (gothiceng.jhf)
 * Fonts 0 and 5..10 keep the 8x8 bitmap. Only ASCII 33..126 draws (95 glyphs a face with the
 * space); other bytes advance by the width of a space and draw nothing.
 *
 * DATA SOURCE AND LICENCE (rip_fontdata.inc, regenerated by tools/gen_rip_font.py):
 *   https://github.com/kamalmostafa/hershey-fonts (the .jhf files in its hershey-fonts directory), also
 *   http://www.whence.com/hershey-fonts/. Copyright 1967 Dr. A. V. Hershey, James Hurt.
 *   Not GPL: the GPL in that package covers its library code; the font data has its own notice
 *   (free for any use, commercial or not, with these acknowledgements, which stay with the data):
 *     - The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the
 *       U. S. National Bureau of Standards.
 *     - The format of the Font data in this distribution was originally created by
 *       James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821.
 *     - The font data may be converted into any other format EXCEPT the format distributed by
 *       the U.S. NTIS (which holds the rights to that particular format). This is not the NTIS format.
 *
 * Geometry: Hershey units, cap top y = -12, baseline y = +9; glyph origin x = left. Size 1 is
 * 1/3 pixel a unit, so a capital is about 7 pixels tall like the 8x8 cell; size s multiplies.
 * The advance is the glyph's (right - left).
 */

#include "rip_fontdata.inc"

/* sentinel for the reachability test: glyphs the stroke code has drawn */
static long rip_font_glyph_count;

long rip_font_stroke_glyphs(void)
{
    return rip_font_glyph_count;
}

int rip_font_is_stroke(int font)
{
    return font >= 1 && font <= 4;
}

static const char *hf_glyph(int style, int ch)
{
    const char *const *tab;
    if (ch < 32 || ch > 126)
        ch = 32;
    switch (style) {
    case 1: tab = hf_triplex; break;
    case 2: tab = hf_small; break;
    case 3: tab = hf_sans; break;
    default: tab = hf_gothic; break;
    }
    return tab[ch - 32];
}

/* hershey units to pixels at size s: v * s / 3, rounded half away from zero */
static int hf_px(int v, int s)
{
    return v >= 0 ? (v * s * 2 + 3) / 6 : -((-v * s * 2 + 3) / 6);
}

/* one glyph at origin (ox, oy), the top left of its text cell, across or up (a quarter turn
 * counter-clockwise like the bitmap) as segments: seg(ud, x0, y0, x1, y1); a lone vertex is a
 * degenerate segment (a dot). Returns the advance in pixels. */
int rip_font_glyph(int font, int ch, int s, int up, int ox, int oy,
                   void (*seg)(void *ud, int x0, int y0, int x1, int y1), void *ud)
{
    const char *g = hf_glyph(font, ch);
    int left = g[0] - 'R', right = g[1] - 'R';
    int have = 0, px = 0, py = 0, x, y, X, Y;
    if (ch >= 33 && ch <= 126)
        rip_font_glyph_count++;
    for (g += 2; g[0] && g[1]; g += 2) {
        if (g[0] == ' ' && g[1] == 'R') {
            have = 0;
            continue;
        }
        x = hf_px(g[0] - 'R' - left, s);
        y = hf_px(g[1] - 'R' + 12, s);
        X = up ? ox + y : ox + x;
        Y = up ? oy - x : oy + y;
        seg(ud, have ? px : X, have ? py : Y, X, Y);
        have = 1;
        px = X;
        py = Y;
    }
    return hf_px(right - left, s);
}
